#!/usr/bin/env bash
# ==============================================================================
# PACT Production Host Preparation Script (Ubuntu 22.04 / 24.04 LTS)
# Prepares host directories, checks prerequisites, and sets up external secrets.
# SAFE & NON-DESTRUCTIVE: Never resets databases, wipes volumes, or destroys data.
# ==============================================================================

set -euo pipefail

ENV_FILE="/etc/pact/pact.env"
ENV_DIR="/etc/pact"
APP_DIR="/opt/pact"

echo "========================================================"
echo " PACT Deployment Setup (Ubuntu Host Environment Check)"
echo "========================================================"

# 1. Check root or sudo privileges
if [[ $EUID -ne 0 ]]; then
  echo "[-] Error: This installation script must be run as root or with sudo to configure /etc/pact and Docker permissions." >&2
  exit 1
fi

# 2. Check for required system utilities
echo "[+] Checking required host utilities..."
MISSING_PKGS=()
for cmd in curl openssl tar grep sed; do
  if ! command -v "$cmd" &>/dev/null; then
    MISSING_PKGS+=("$cmd")
  fi
done

if [[ ${#MISSING_PKGS[@]} -gt 0 ]]; then
  echo "[!] Missing required host utilities: ${MISSING_PKGS[*]}"
  echo "[+] Installing missing prerequisites via apt-get..."
  apt-get update -y
  apt-get install -y "${MISSING_PKGS[@]}"
fi

# 3. Check Docker and Docker Compose v2
echo "[+] Checking Docker engine and compose plugin..."
if ! command -v docker &>/dev/null; then
  echo "[!] Docker not detected. Please install Docker Engine for Ubuntu:"
  echo "    https://docs.docker.com/engine/install/ubuntu/"
  echo "    Quick install:"
  echo "      curl -fsSL https://get.docker.com | sh"
  echo "      systemctl enable --now docker"
  exit 1
fi

if ! docker compose version &>/dev/null; then
  echo "[!] Docker Compose v2 plugin ('docker compose') is required."
  echo "    Install via: apt-get install -y docker-compose-plugin"
  exit 1
fi

echo "[✓] Docker $(docker --version) detected."
echo "[✓] Compose $(docker compose version) detected."

# 4. Prepare application and secrets directory
echo "[+] Configuring directories..."
mkdir -p "$ENV_DIR"
mkdir -p "$APP_DIR"
chmod 700 "$ENV_DIR"

# 5. Initialize external secret file if not present
if [[ ! -f "$ENV_FILE" ]]; then
  echo "[+] Generating initial production secrets in $ENV_FILE..."
  SESSION_SECRET_GEN=$(openssl rand -hex 32)
  PACT_RUNTIME_TOKEN_GEN=$(openssl rand -hex 32)

  cat <<EOF > "$ENV_FILE"
# ==============================================================================
# PACT Production Environment Secrets
# Auto-generated by install.sh on $(date -u +"%Y-%m-%d %H:%M:%SZ")
# File permissions: 0600 (owner-only read/write)
# ==============================================================================

# Required session HMAC signing secret (minimum 32 bytes)
SESSION_SECRET=${SESSION_SECRET_GEN}

# Required inter-service bearer token between web and Eve agent runtimes
PACT_RUNTIME_TOKEN=${PACT_RUNTIME_TOKEN_GEN}

# Public domain or host for Caddy (defaults to localhost, or set to domain/IP)
PACT_DOMAIN=localhost

# OpenAI API key (leave blank for deterministic $0 graph-grounded mode)
OPENAI_API_KEY=

# Model and budget configuration
OPENAI_MODEL=gpt-6.1-sol
PACT_API_BUDGET_USD=5
PACT_AGENT_GRAPH=pact_agent
PACT_BUDGET_GRAPH=pact_budget
EOF

  chmod 600 "$ENV_FILE"
  echo "[✓] Created $ENV_FILE with secure 0600 permissions."
else
  echo "[✓] Existing secret file detected at $ENV_FILE (preserved, not overwritten)."
  chmod 600 "$ENV_FILE"
fi

# 6. Verify required secrets in ENV_FILE
echo "[+] Validating secret file completeness..."
if ! grep -q "^SESSION_SECRET=.\{32,\}" "$ENV_FILE"; then
  echo "[-] Warning: SESSION_SECRET in $ENV_FILE appears missing or shorter than 32 characters." >&2
fi

if ! grep -q "^PACT_RUNTIME_TOKEN=.\{16,\}" "$ENV_FILE"; then
  echo "[-] Warning: PACT_RUNTIME_TOKEN in $ENV_FILE appears missing or unconfigured." >&2
fi

echo "========================================================"
echo " Installation check passed successfully!"
echo " Next step:"
echo "   1. Review or customize $ENV_FILE (e.g. set PACT_DOMAIN or OPENAI_API_KEY)"
echo "   2. Run deploy.sh from the repository or app directory:"
echo "      sudo bash scripts/deploy/deploy.sh"
echo "========================================================"
